/*
Question 4: Employee Hierarchy & Performance

Task:
For each manager in the Sales department (department_id = 1), calculate:

Number of direct reports
Average performance score across ALL their direct reports (across all quarters in 2024)
Total revenue generated by their team in 2024
*/

-- Solution:

SELECT 
    m.first_name || ' ' || m.last_name as full_name,
    m.employee_id,
    COUNT(DISTINCT e.employee_id) as direct_reports,
    ROUND(AVG(ep.performance_score), 2) AS avg_performance_score,
    SUM(ep.revenue_generated) as team_revenue_2024
FROM employees as e 
join employees as m            
    on m.employee_id = e.manager_id
JOIN employee_performance as ep
    on ep.employee_id = e.employee_id
    AND ep.review_year = 2024
WHERE e.department_id = 1
GROUP BY m.first_name, m.last_name, m.employee_id;
