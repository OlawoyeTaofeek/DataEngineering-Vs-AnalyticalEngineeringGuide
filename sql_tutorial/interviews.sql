/*
Task:
Find the total revenue generated from completed orders only for each product category. Display the category name and total revenue, sorted by revenue in descending order.

Expected Output Columns: category_name, total_revenue

The test also says to use order_items.unit_price (and quantity) when calculating revenue from completed orders.
*/

SELECT 
    pc.category_name, 
    SUM(oi.unit_price * oi.quantity) AS total_revenue
FROM orders as o
JOIN order_items as oi
    ON o.order_id = oi.order_id
JOIN products as p
    ON oi.product_id = p.product_id
JOIN product_categories as pc
    ON p.category_id = pc.category_id
WHERE o.status = 'completed'
GROUP BY pc.category_name
ORDER BY total_revenue DESC;

